from datetime import datetime
from typing import Optional, Dict, Any


class ReportGenerator:
    """Generate medical reports for kidney and tumor segmentation results."""
    
    def __init__(self, patient_id: Optional[str] = None, 
                 patient_name: Optional[str] = None):
        """
        Args:
            patient_id: Optional patient ID
            patient_name: Optional patient name
        """
        self.patient_id = patient_id or "Unknown"
        self.patient_name = patient_name or "Unknown"
        self.timestamp = datetime.now()
        
    def generate_markdown_report(self, 
                                 tumor_detected: bool,
                                 tumor_area_pixels: int,
                                 image_size: int = 256,
                                 tumor_percentage: Optional[float] = None,
                                 classifications: Optional[Dict[str, float]] = None) -> str:
        """
        Generate a markdown format report.
        
        Args:
            tumor_detected: Whether tumor was detected
            tumor_area_pixels: Area of tumor in pixels
            image_size: Input image size (pixels)
            tumor_percentage: Percentage of image containing tumor
            classifications: Dict with class probabilities
            
        Returns:
            Markdown formatted report as string
        """
        # Calculate tumor percentage if not provided
        if tumor_percentage is None:
            total_pixels = image_size * image_size
            tumor_percentage = (tumor_area_pixels / total_pixels) * 100
            
        # Calculate tumor area in cm² (assuming pixel size, for illustration)
        # Assuming 1 pixel = 0.1mm (typical CT resolution after preprocessing)
        pixel_size_mm = 0.1
        tumor_area_mm2 = tumor_area_pixels * (pixel_size_mm ** 2)
        tumor_area_cm2 = tumor_area_mm2 / 100
        
        # Build report
        report = f"""# Medical Report: Kidney & Tumor Segmentation

## Report Information
- **Generated**: {self.timestamp.strftime('%Y-%m-%d %H:%M:%S')}
- **Patient ID**: {self.patient_id}
- **Patient Name**: {self.patient_name}
- **Modality**: CT Scan

## Analysis Results

### Tumor Detection
- **Status**: {'**TUMOR DETECTED** ⚠️' if tumor_detected else 'No tumor detected'}
- **Confidence**: {'High' if tumor_detected else 'N/A'}

### Quantitative Measurements
- **Tumor Area (pixels)**: {tumor_area_pixels:,}
- **Tumor Area (cm²)**: {tumor_area_cm2:.2f}
- **Tumor Coverage**: {tumor_percentage:.2f}%

### Segmentation Classes
"""
        if classifications:
            report += "\n| Class | Probability |\n"
            report += "|-------|-------------|\n"
            for class_name, prob in classifications.items():
                report += f"| {class_name} | {prob:.2%} |\n"
        else:
            # Default class list
            report += "\n- **Background**: Healthy tissue\n"
            report += "- **Kidney**: Healthy kidney tissue\n"
            report += "- **Tumor**: Abnormal growth detected\n"
        
        report += """
## Clinical Interpretation

"""
        if tumor_detected:
            report += f"""A tumor has been detected in the analyzed CT slice with a measured area of {tumor_area_cm2:.2f} cm². 
This represents {tumor_percentage:.2f}% of the segmented region.

**Recommendations**:
1. Consult with a radiologist for detailed analysis
2. Compare with previous scans for progression tracking
3. Consider follow-up imaging studies
4. Discuss treatment options with oncology team
"""
        else:
            report += """No tumor detected in the analyzed CT slice. The kidneys appear normal in this section.

**Recommendations**:
1. Continue with routine follow-up as recommended by physician
2. Maintain healthy lifestyle
3. Schedule periodic monitoring as clinically indicated
"""
        
        report += f"""
## Technical Details
- **Model**: HybridUNet with Transformer Bottleneck
- **Input Resolution**: {image_size}x{image_size} pixels
- **Output Classes**: 3 (Background, Kidney, Tumor)
- **Segmentation Method**: Deep Learning based semantic segmentation

---
*This report is generated by an AI model and should be reviewed by a qualified medical professional.*
"""
        
        return report
    
